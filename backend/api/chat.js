function corsHeaders(origin, allowed) {
  return {
    // Echo only an origin we actually allow, so a cached response can never
    // hand one site's permission to another. Vary keeps caches honest about
    // this header changing per request.
    'Access-Control-Allow-Origin': allowed ? origin : 'null',
    'Access-Control-Allow-Methods': 'POST, OPTIONS',
    'Access-Control-Allow-Headers': 'Content-Type',
    'Access-Control-Max-Age': '86400',
    'Vary': 'Origin',
    'Content-Type': 'application/json',
  };
}

function json(body, status, ctx) {
  return new Response(JSON.stringify(body), {
    status,
    headers: corsHeaders(ctx.origin, ctx.allowed),
  });
}

/* Best-effort per-IP limit. State is per-instance and lost when the instance
   is recycled, so it will not stop a distributed flood -- it stops the
   realistic one: a single script hammering the endpoint and burning a
   free-tier quota the whole site depends on. */
const hits = new Map();

function rateLimited(key, limit, windowMs) {
  const now = Date.now();
  const recent = (hits.get(key) || []).filter(ts => now - ts < windowMs);
  recent.push(now);
  hits.set(key, recent);
  if (hits.size > 5000) {
    for (const [k, stamps] of hits) {
      if (!stamps.length || now - stamps[stamps.length - 1] > windowMs) hits.delete(k);
    }
  }
  return recent.length > limit;
}

async function readJson(request) {
  const declared = Number(request.headers.get('content-length') || 0);
  if (declared > BODY_LIMIT) return null;
  try {
    const text = await request.text();
    if (text.length > BODY_LIMIT) return null;
    const parsed = JSON.parse(text);
    return parsed && typeof parsed === 'object' ? parsed : null;
  } catch {
    return null;
  }
}

export default async function handler(request) {
  const origin = request.headers.get('origin');
  const list = (process.env.ALLOWED_ORIGIN || '').split(',').map(s => s.trim()).filter(Boolean);
  // Unset means "allow anything", which keeps a fresh deployment working before
  // the variable is configured. Once set, it is enforced here rather than left
  // to the browser: CORS only makes a browser discard a response this function
  // has already paid for, and curl ignores it completely.
  const allowed = !list.length || (!!origin && list.includes(origin));
  const ctx = {
    origin: origin || '*',
    allowed,
    ip: request.headers.get('x-forwarded-for') || request.headers.get('cf-connecting-ip') || 'unknown',
  };

  if (request.method === 'OPTIONS') {
    return new Response(null, { status: 204, headers: corsHeaders(ctx.origin, allowed) });
  }
  if (!allowed) {
    console.warn('Blocked origin', origin);
    return json({ error: 'Forbidden' }, 403, ctx);
  }
  if (request.method !== 'POST') {
    return json({ error: 'Method not allowed' }, 405, ctx);
  }
  if (!process.env.GEMINI_API_KEY) {
    // Configuration problem, not the visitor's fault — do not leak details.
    console.error('GEMINI_API_KEY is not set');
    return json({ error: 'Assistant unavailable' }, 503, ctx);
  }
  if (rateLimited('chat:' + ctx.ip, 12, 60 * 1000)) {
    return json({ error: 'Too many requests' }, 429, ctx);
  }

  const payload = await readJson(request);
  if (!payload) return json({ error: 'Invalid JSON' }, 400, ctx);

  const lang = payload.lang === 'ar' ? 'ar' : 'en';
  const incoming = Array.isArray(payload.messages) ? payload.messages : [];
  if (!incoming.length) return json({ error: 'No messages' }, 400, ctx);

  // Accept only the shape we expect; drop anything else the client sent.
  // Gemini says "model" where the client says "assistant" -- translate the
  // roles and wrap each turn's text in "parts".
  const contents = incoming
    .slice(-MAX_MESSAGES)
    .filter(m => m && (m.role === 'user' || m.role === 'assistant') && typeof m.content === 'string')
    .map(m => ({
      role: m.role === 'assistant' ? 'model' : 'user',
      parts: [{ text: m.content.slice(0, MAX_CHARS) }],
    }));

  if (!contents.length) return json({ error: 'No usable messages' }, 400, ctx);

  const model = process.env.GEMINI_MODEL || DEFAULT_MODEL;
  const url = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent`;

  try {
    const res = await fetch(url, {
      method: 'POST',
      headers: {
        'x-goog-api-key': process.env.GEMINI_API_KEY,
        'Content-Type': 'application/json',
      },
      body: JSON.stringify({
        contents,
        systemInstruction: { parts: [{ text: systemPrompt(lang) }] },
        generationConfig: { temperature: 0.3, maxOutputTokens: MAX_TOKENS },
      }),
    });

    if (!res.ok) {
      console.error('Gemini API error', res.status, (await res.text()).slice(0, 500));
      return json({ error: 'Assistant unavailable' }, 502, ctx);
    }

    const data = await res.json();
    const reply = data?.candidates?.[0]?.content?.parts?.map(p => p.text || '').join('').trim();
    if (!reply) return json({ error: 'Empty reply' }, 502, ctx);

    return json({ reply }, 200, ctx);
  } catch (err) {
    console.error('Proxy failure', err);
    return json({ error: 'Assistant unavailable' }, 502, ctx);
  }
}

