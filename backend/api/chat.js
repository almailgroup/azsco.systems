/**
 * AZSCO Assistant — server-side proxy for the Gemini API.
 *
 * The API key lives here, in the GEMINI_API_KEY environment variable, and never
 * reaches the browser. The static site posts {lang, messages} to this endpoint.
 *
 * Deploy target: any host that runs a Node serverless function with the Web
 * Request/Response API (Vercel, Netlify Functions v2, Deno Deploy). The
 * Cloudflare Workers variant in backend/workers/chat-worker.js is the one this
 * site actually runs, and it also carries the contact form's /contact route;
 * this file is the chat half alone, for a host where Workers is not an option.
 *
 * Environment variables:
 *   GEMINI_API_KEY  required; your key from https://aistudio.google.com/apikey
 *                   (no payment method needed for the free tier)
 *   ALLOWED_ORIGIN  strongly recommended; comma-separated origins allowed to
 *                   call this endpoint. Requests from anywhere else are refused
 *                   before Gemini is called. Unset means anyone may call it and
 *                   spend the quota.
 *   GEMINI_MODEL    optional; defaults to DEFAULT_MODEL below.
 *
 * The prompt block below is generated. Edit CHAT_FACTS / CHAT_RULES in
 * tools/build.py and run `python3 tools/build.py`, which rewrites it here and in
 * backend/workers/chat-worker.js, then redeploy. Editing it by hand means the
 * next build silently reverts the change.
 *
 * Why Gemini and not Mistral: Mistral's free tier rate-limits far too
 * aggressively for live visitor traffic (a single test message could exhaust
 * it). Google AI Studio's free tier suits light, ongoing production use --
 * see https://ai.google.dev/gemini-api/docs/models for current limits.
 */

const DEFAULT_MODEL = 'gemini-2.5-flash';

const MAX_CHARS = 1000;     // per message
const MAX_MESSAGES = 40;    // per request
const MAX_TOKENS = 500;     // per reply
const BODY_LIMIT = 100_000; // bytes of request body we will read at all

